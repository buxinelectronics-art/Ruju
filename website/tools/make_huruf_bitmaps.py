#!/usr/bin/env python3
"""Generate huruf_bitmaps.h for the Quran Player OLED (SH1106).

Uses Noto Naskh Arabic (SIL Open Font License) plus arabic-reshaper / python-bidi.
Run from repo root:
  python website/tools/make_huruf_bitmaps.py
"""
from __future__ import annotations

import pathlib

from PIL import Image, ImageDraw, ImageFont
import arabic_reshaper
from bidi.algorithm import get_display

ROOT = pathlib.Path(__file__).resolve().parents[2]
FONT = pathlib.Path(__file__).with_name("NotoNaskhArabic-Regular.ttf")
OUT = ROOT / "QuranPlayerV7" / "huruf_bitmaps.h"

# 01..28 English names shown on the OLED (ASCII)
LETTERS = [
    ("Alif", "ا"),
    ("Ba", "ب"),
    ("Ta", "ت"),
    ("Tha", "ث"),
    ("Jim", "ج"),
    ("Ha", "ح"),
    ("Kha", "خ"),
    ("Dal", "د"),
    ("Dhal", "ذ"),
    ("Ra", "ر"),
    ("Zay", "ز"),
    ("Sin", "س"),
    ("Shin", "ش"),
    ("Sad", "ص"),
    ("Dad", "ض"),
    ("Tah", "ط"),
    ("Zah", "ظ"),
    ("Ayn", "ع"),
    ("Ghayn", "غ"),
    ("Fa", "ف"),
    ("Qaf", "ق"),
    ("Kaf", "ك"),
    ("Lam", "ل"),
    ("Mim", "م"),
    ("Nun", "ن"),
    ("Ha2", "ه"),
    ("Waw", "و"),
    ("Ya", "ي"),
]

W = 40
H = 40


def to_xbm_bytes(img: Image.Image) -> list[int]:
    """Pack monochrome image into XBM-style bytes (LSB first per row byte)."""
    img = img.convert("1")
    out = []
    for y in range(H):
        byte = 0
        bit = 0
        for x in range(W):
            # Pillow 1-bit: 0=black ink after our invert step
            on = img.getpixel((x, y)) == 0
            if on:
                byte |= 1 << bit
            bit += 1
            if bit == 8:
                out.append(byte)
                byte = 0
                bit = 0
        if bit:
            out.append(byte)
    return out


def render_letter(ch: str, font: ImageFont.FreeTypeFont) -> list[int]:
    reshaped = arabic_reshaper.reshape(ch)
    shown = get_display(reshaped)
    canvas = Image.new("L", (W * 2, H * 2), 255)
    draw = ImageDraw.Draw(canvas)
    bbox = draw.textbbox((0, 0), shown, font=font)
    tw, th = bbox[2] - bbox[0], bbox[3] - bbox[1]
    x = (canvas.size[0] - tw) // 2 - bbox[0]
    y = (canvas.size[1] - th) // 2 - bbox[1]
    draw.text((x, y), shown, fill=0, font=font)
    # Crop content and fit into W x H
    bb = canvas.getbbox()
    if not bb:
        return [0] * ((W + 7) // 8 * H)
    cropped = canvas.crop(bb)
    fitted = Image.new("L", (W, H), 255)
    cw, chh = cropped.size
    scale = min(W / cw, H / chh, 1.0)
    nw, nh = max(1, int(cw * scale)), max(1, int(chh * scale))
    resized = cropped.resize((nw, nh), Image.Resampling.LANCZOS)
    fitted.paste(resized, ((W - nw) // 2, (H - nh) // 2))
    # Threshold to 1-bit
    bw = fitted.point(lambda p: 0 if p < 128 else 255, mode="1")
    return to_xbm_bytes(bw)


def main() -> None:
    if not FONT.exists():
        raise SystemExit(f"Missing font: {FONT}")
    font = ImageFont.truetype(str(FONT), 48)
    lines = [
        "/* Auto-generated by website/tools/make_huruf_bitmaps.py — do not edit by hand. */",
        "/* Font: Noto Naskh Arabic (SIL Open Font License 1.1) */",
        "#pragma once",
        f"#define HURUF_W {W}",
        f"#define HURUF_H {H}",
        f"#define HURUF_COUNT {len(LETTERS)}",
        "static const char* const HURUF_NAMES[HURUF_COUNT] = {",
    ]
    for name, _ in LETTERS:
        lines.append(f'  "{name}",')
    lines.append("};")
    lines.append("static const uint8_t HURUF_BITS[HURUF_COUNT][(HURUF_W + 7) / 8 * HURUF_H] = {")
    for i, (name, ch) in enumerate(LETTERS):
        bits = render_letter(ch, font)
        rows = []
        for j in range(0, len(bits), 12):
            chunk = ", ".join(f"0x{b:02X}" for b in bits[j : j + 12])
            rows.append("    " + chunk)
        body = ",\n".join(rows)
        lines.append(f"  {{ /* {i + 1:02d} {name} */")
        lines.append(body)
        lines.append("  },")
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", OUT, "bytes", OUT.stat().st_size)


if __name__ == "__main__":
    main()
